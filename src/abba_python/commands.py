    def export_atlas_to_imagej(self, *,
            atlas_channels_csv: str = '*',
            image_name: str = 'Atlas',
            interpolate: bool = False,
            pixel_size_um: float = 20.0) -> Any:
        """
        ABBA - Export Atlas to ImageJ

        Exports the atlas section at the position of each selected slice as an ImageJ image, one plane per
        slice, within the current region of interest. Same geometry as 'Export Registered Slices to ImageJ'
        with the same pixel size, so both images can be overlaid.

        Parameters
        ----------
        atlas_channels_csv : str
            Atlas channels. 0-based indices of the atlas channels to export, comma separated (e.g. '0,1'),
            or '*' for all channels. Depending on the atlas, channels include anatomical images, region
            borders, atlas coordinates, a left/right indicator and region labels.
        image_name : str
            Image name. Title of the exported ImageJ image.
        interpolate : bool
            Interpolate. If checked, pixels are linearly interpolated when resampled; otherwise the nearest
            pixel is used (keep it unchecked for label channels).
        pixel_size_um : float
            Pixel size (micrometers). Pixel size of the exported image.

        Returns
        -------
        Any
            Image. Exported atlas image: one channel per atlas channel, one plane per selected slice.
        """
        return self._run_command('ch.epfl.biop.atlas.aligner.command.ExportAtlasToImageJCommand', {
            'mp': self.mp,
            'atlas_channels_csv': atlas_channels_csv,
            'image_name': image_name,
            'interpolate': interpolate,
            'pixel_size_um': pixel_size_um,
        }, output='image')

    def export_deformation_field_to_imagej(self, *,
            resolution_level: int,
            downsampling: int = 1,
            max_number_of_iterations: int = 200) -> Any:
        """
        ABBA - Export Atlas Coordinates of Original Slices to ImageJ

        For each selected slice, exports a 3-channel (x, y, z) 32-bit ImageJ image with the same pixels as
        the original unregistered slice image: each pixel holds its atlas coordinates, in mm. Waits for the
        registrations of the slices to be done.

        Parameters
        ----------
        resolution_level : int
            Resolution level. Resolution level of the original image the exported image matches: 0 = full
            resolution, 1 = first downscaled level, etc. Must exist in the slice files.
        downsampling : int
            Additional downsampling factor. Integer factor to further downsample the exported image, on top
            of the resolution level. 1 = no downsampling.
        max_number_of_iterations : int
            Max iterations for transform inversion. Maximum number of iterations used to numerically invert
            non-linear (spline) registrations. Increase it if the inversion does not converge. Default 200.

        Returns
        -------
        Any
            Images. One coordinates image per selected slice.
        """
        return self._run_command('ch.epfl.biop.atlas.aligner.command.ExportDeformationFieldToImageJCommand', {
            'mp': self.mp,
            'resolution_level': resolution_level,
            'downsampling': downsampling,
            'max_number_of_iterations': max_number_of_iterations,
        }, output='images')

